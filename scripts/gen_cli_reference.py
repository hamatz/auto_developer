#!/usr/bin/env python3
"""Generate docs/cli.md directly from auto_developer.cli.build_parser()."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = REPO_ROOT / "src"
if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from auto_developer.cli import build_parser


def _format_action_flags(action: argparse.Action) -> str:
    if action.option_strings:
        flags = ", ".join(action.option_strings)
        if action.nargs != 0 and not isinstance(
            action, (argparse._StoreTrueAction, argparse._StoreFalseAction, argparse._HelpAction, argparse._VersionAction)
        ):
            metavar = action.metavar or action.dest.upper()
            if isinstance(metavar, tuple):
                metavar = " ".join(metavar)
            flags = f"{flags} {metavar}"
        return f"`{flags}`"
    return f"`{action.dest}`"


def _format_default(action: argparse.Action) -> str:
    default = action.default
    if default is argparse.SUPPRESS or default is None:
        return "-"
    if isinstance(default, Path):
        if default == Path.cwd():
            return "`.` (cwd)"
        return f"`{default}`"
    if default == "":
        return "`\"\"`"
    return f"`{default}`"


def _render_parser_section(parser: argparse.ArgumentParser, heading: str, level: int = 2) -> list[str]:
    lines: list[str] = []
    prefix = "#" * level
    lines.append(f"{prefix} `{heading}`")
    lines.append("")
    if parser.description:
        lines.append(parser.description)
        lines.append("")

    positionals: list[argparse.Action] = []
    optionals: list[argparse.Action] = []
    subparsers_actions: list[argparse._SubParsersAction[argparse.ArgumentParser]] = []

    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            subparsers_actions.append(action)
        elif action.option_strings:
            if isinstance(action, argparse._HelpAction):
                continue
            optionals.append(action)
        else:
            positionals.append(action)

    if positionals or optionals:
        lines.append("| Argument / Option | Required | Default | Description |")
        lines.append("| --- | --- | --- | --- |")
        for act in positionals + optionals:
            req = "Yes" if getattr(act, "required", False) or (not act.option_strings and act.nargs not in ("?", "*")) else "No"
            help_text = (act.help or "").replace("\n", " ").replace("|", "\\|")
            lines.append(f"| {_format_action_flags(act)} | {req} | {_format_default(act)} | {help_text} |")
        lines.append("")

    for sub_act in subparsers_actions:
        for name, subparser in sub_act.choices.items():
            lines.extend(_render_parser_section(subparser, f"{heading} {name}", level=min(level + 1, 4)))

    return lines


def render_cli_reference() -> str:
    """Render full Markdown CLI reference from argparse."""
    parser = build_parser()
    lines = [
        "<!-- Generated by scripts/gen_cli_reference.py from auto_developer.cli.build_parser(). Do not edit manually. -->",
        "",
        "# Auto Developer CLI Reference",
        "",
    ]
    lines.extend(_render_parser_section(parser, "auto-dev", level=2))
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate or verify docs/cli.md from argparse.")
    ap.add_argument("--check", action="store_true", help="Exit non-zero if docs/cli.md is out of date.")
    ap.add_argument("--output", type=Path, default=REPO_ROOT / "docs" / "cli.md")
    args = ap.parse_args(argv)

    rendered = render_cli_reference()
    if args.check:
        if not args.output.is_file():
            print(f"MISSING: {args.output}", file=sys.stderr)
            return 1
        current = args.output.read_text(encoding="utf-8")
        if current != rendered:
            print(f"OUT_OF_SYNC: {args.output} does not match argparse definition.", file=sys.stderr)
            return 1
        print(f"OK: {args.output} is up to date.")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8")
    print(f"WROTE: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
